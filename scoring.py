"""Combine directional evidence conservatively and explain it to a writer."""

import math
import config

HUMAN_LABEL = "We think this was probably written by a person. This estimate does not verify who wrote it. You can ask for a review if it seems wrong."
UNSURE_LABEL = "We cannot reliably tell how this was written. This is not an accusation. You can ask for a review and explain your writing process."
AI_LABEL = "We think this may have been generated by AI. This estimate can be wrong and is not proof. If you wrote it, you can appeal and explain your writing process."


def _validate(score: float) -> None:
    if not math.isfinite(score) or not 0 <= score <= 1:
        raise ValueError("Scores must be finite numbers between 0 and 1.")


def combine_signals(model_score: float, style_score: float) -> float:
    """70% model, 30% style; a >=0.50 disagreement stays unsure."""
    _validate(model_score)
    _validate(style_score)
    score = config.WEIGHT_MODEL_SIGNAL * model_score + config.WEIGHT_STYLE_SIGNAL * style_score
    # Round the gap first: in floating point 0.95 - 0.45 is 0.49999999999999994,
    # which slipped past this check and turned a 0.50 disagreement into an AI label.
    if round(abs(model_score - style_score), 6) >= config.DISAGREEMENT_THRESHOLD:
        score = min(max(score, config.DISAGREEMENT_FLOOR), config.DISAGREEMENT_CEILING)
    return round(score, 4)


def score_to_label(score: float) -> tuple[str, str]:
    _validate(score)
    if score <= config.HUMAN_THRESHOLD:
        return "human", HUMAN_LABEL
    if score >= config.AI_THRESHOLD:
        return "ai", AI_LABEL
    return "unsure", UNSURE_LABEL


def label_ranges() -> list[tuple[str, str]]:
    return [
        ("high-confidence human", f"0 <= score <= {config.HUMAN_THRESHOLD:.2f}"),
        ("unsure", f"{config.HUMAN_THRESHOLD:.2f} < score < {config.AI_THRESHOLD:.2f}"),
        ("high-confidence AI", f"{config.AI_THRESHOLD:.2f} <= score <= 1"),
    ]


if __name__ == "__main__":
    for name, interval in label_ranges():
        print(f"{name}: {interval}")
